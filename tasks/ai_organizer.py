"""
Simple 'Generative AI' task organizer.

Two modes:
1. If an OPENAI_API_KEY environment variable is set, the daily plan is
   generated by calling OpenAI's chat API.
2. Otherwise (the default, so the project works offline out of the box),
   a built-in rule-based organizer produces the plan and priority
   suggestions using urgency/priority scoring and simple keyword rules.

This keeps the "Generative AI feature" requirement satisfied even
without any API key or internet access, while making it easy to plug
in a real LLM later by just setting the environment variable.
"""
import os
from datetime import date


def suggest_priority(title, description=""):
    """Suggest a priority for a task based on simple keyword rules."""
    text = f"{title} {description}".lower()

    high_keywords = [
        'urgent', 'asap', 'exam', 'deadline', 'important', 'critical',
        'due today', 'interview', 'emergency', 'submit', 'presentation',
    ]
    low_keywords = ['someday', 'maybe', 'later', 'optional', 'idea', 'someday-maybe']

    if any(word in text for word in high_keywords):
        return 'high'
    if any(word in text for word in low_keywords):
        return 'low'
    return 'medium'


def _score_task(task, today):
    """Higher score = should be done sooner."""
    weight = {'high': 30, 'medium': 20, 'low': 10}
    score = weight.get(task.priority, 20)

    if task.deadline:
        days_left = (task.deadline - today).days
        if days_left < 0:
            score += 100  # overdue
        elif days_left == 0:
            score += 60
        elif days_left <= 2:
            score += 35
        elif days_left <= 7:
            score += 10
    return score


def _rule_based_plan(tasks):
    """Build a ranked daily plan with a short reason for each task."""
    today = date.today()
    pending = [t for t in tasks if not t.completed]

    if not pending:
        return "You have no pending tasks — enjoy your day! 🎉", []

    ranked = sorted(pending, key=lambda t: -_score_task(t, today))

    lines = ["Here's a suggested order for today, based on priority and deadlines:", ""]
    suggestions = []
    for i, task in enumerate(ranked, start=1):
        reasons = []
        if task.deadline:
            days_left = (task.deadline - today).days
            if days_left < 0:
                reasons.append(f"overdue by {abs(days_left)} day(s)")
            elif days_left == 0:
                reasons.append("due today")
            elif days_left <= 2:
                reasons.append(f"due in {days_left} day(s)")
            else:
                reasons.append(f"due {task.deadline.strftime('%b %d')}")
        reasons.append(f"{task.get_priority_display().lower()} priority")
        reason_text = ", ".join(reasons)

        lines.append(f"{i}. {task.title} — {reason_text}")
        suggestions.append({'task': task, 'rank': i, 'reason': reason_text})

    return "\n".join(lines), suggestions


def _ai_plan_via_openai(tasks, api_key):
    """Optional: use a real LLM if OPENAI_API_KEY is configured."""
    import openai

    pending = [t for t in tasks if not t.completed]
    if not pending:
        return "You have no pending tasks — enjoy your day!"

    task_lines = "\n".join(
        f"- {t.title} (priority: {t.priority}, deadline: {t.deadline or 'none'})"
        for t in pending
    )
    prompt = (
        "You are a helpful assistant that organizes a to-do list into a short, "
        "practical daily plan. Given these tasks, suggest an order to tackle "
        "them in and a one-line reason for each. Keep the whole answer under "
        "150 words.\n\nTasks:\n" + task_lines
    )

    client = openai.OpenAI(api_key=api_key)
    response = client.chat.completions.create(
        model="gpt-3.5-turbo",
        messages=[{"role": "user", "content": prompt}],
        max_tokens=400,
        temperature=0.4,
    )
    return response.choices[0].message.content.strip()


def generate_daily_plan(tasks):
    """
    Main entry point used by the view. Returns a plain-text daily plan.
    Falls back to the rule-based organizer if no API key is set, or if
    the API call fails for any reason (e.g. no internet access).
    """
    api_key = os.environ.get('OPENAI_API_KEY')
    if api_key:
        try:
            return _ai_plan_via_openai(tasks, api_key)
        except Exception:
            pass  # silently fall back — the feature should never break the page

    plan_text, _ = _rule_based_plan(tasks)
    return plan_text
